export function translateUI(text: string, lang: SupportedLanguage = 'en'): string {
  if (!text || lang === 'en') return text;
  if (UI_DICTIONARY[lang]?.[text]) {
    return UI_DICTIONARY[lang][text];
  }
  const keys = Object.keys(UI_DICTIONARY[lang] || {});
  const matchedKey = keys.find((k) => k.toLowerCase() === text.toLowerCase());
  if (matchedKey && UI_DICTIONARY[lang][matchedKey]) {
    return UI_DICTIONARY[lang][matchedKey];
  }
  return text;
}

export function getLanguageInstruction(lang: SupportedLanguage = 'en'): string {
  switch (lang) {
    case 'hi':
      return 'Please respond in fluent Hindi (Devanagari script) with clear explanations and NCERT textbook terminology.';
    case 'hinglish':
      return 'Please respond in natural Hinglish (mix of conversational English and Hindi written in Latin script) so it is very easy for Indian students to understand.';
    case 'ta':
      return 'Please respond in clear Tamil script with accurate scientific terms and NCERT concepts.';
    case 'te':
      return 'Please respond in clear Telugu script with accurate scientific terms and NCERT concepts.';
    case 'mr':
      return 'Please respond in clear Marathi script (Devanagari) with accurate scientific terms and NCERT concepts.';
    case 'en':
    default:
      return 'Please respond in clear, student-friendly English with accurate NCERT textbook concepts.';
  }
}
