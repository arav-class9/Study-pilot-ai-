/**
 * Filter curriculum chapters by Class Level, Board, and Subject
 */
export function getCurriculumChapters(
  classLevel: ClassLevel,
  board: string = 'CBSE',
  subjectId?: SubjectId
): Chapter[] {
  return MASTER_CURRICULUM_DATABASE.filter((chapter) => {
    // Match class level
    if (chapter.classLevel !== classLevel) return false;

    // Match board: if chapter has 'ALL' or matching board id, it matches
    const chapterBoard = (chapter.board || 'ALL').toUpperCase();
    const targetBoard = (board || 'CBSE').toUpperCase();
    const boardMatches =
      chapterBoard === 'ALL' ||
      chapterBoard === targetBoard ||
      (targetBoard === 'BSEB' && (chapterBoard === 'STATE' || chapterBoard === 'CBSE')) ||
      (targetBoard === 'STATE' && chapterBoard === 'CBSE');

    if (!boardMatches) return false;

    // Match subject if specified
    if (subjectId && chapter.subjectId !== subjectId) return false;

    return true;
  });
}

/**
 * Get available subjects for Class + Board
 */
export function getCurriculumSubjects(classLevel: ClassLevel, board: string = 'CBSE'): SubjectMeta[] {
  const subjectIds = getSubjectsForClassAndBoard(classLevel, board);
  return subjectIds.map((id) => ALL_SUBJECTS_META[id]).filter(Boolean);
}

/**
 * Find a specific chapter by ID
 */
export function getChapterById(chapterId: string): Chapter | undefined {
  return MASTER_CURRICULUM_DATABASE.find((c) => c.id === chapterId);
}

/**
 * Get topics for a specific chapter
 */
export function getTopicsForChapter(chapterId: string): Topic[] {
  const chapter = getChapterById(chapterId);
  return chapter?.topics || [];
}

/**
 * Search chapters across curriculum
 */
export function searchCurriculum(
  query: string,
  classLevel?: ClassLevel,
  board?: string,
  subjectId?: SubjectId
): Chapter[] {
  const cleanQ = query.trim().toLowerCase();
  if (!cleanQ) {
    if (classLevel && board) {
      return getCurriculumChapters(classLevel, board, subjectId);
    }
    return MASTER_CURRICULUM_DATABASE;
  }

  return MASTER_CURRICULUM_DATABASE.filter((ch) => {
    if (classLevel && ch.classLevel !== classLevel) return false;
    if (subjectId && ch.subjectId !== subjectId) return false;

    const matchesName = ch.name.toLowerCase().includes(cleanQ);
    const matchesDesc = ch.description.toLowerCase().includes(cleanQ);
    const matchesTopic = ch.topics.some(
      (t) =>
        t.name.toLowerCase().includes(cleanQ) ||
        t.keyConcepts.some((k) => k.toLowerCase().includes(cleanQ))
    );

    return matchesName || matchesDesc || matchesTopic;
  });
}
