/**
 * Returns the relevant subject IDs for a given Class Level and Board
 */
export function getSubjectsForClassAndBoard(classLevel: ClassLevel, board: string = 'CBSE'): SubjectId[] {
  const c = parseInt(classLevel, 10);
  if (c >= 1 && c <= 5) {
    return ['math', 'evs', 'english', 'hindi'];
  }
  if (c >= 6 && c <= 8) {
    return ['math', 'science', 'social_science', 'english', 'hindi', 'computer'];
  }
  if (c >= 9 && c <= 10) {
    return ['math', 'science', 'social_science', 'english', 'hindi', 'computer'];
  }
  if (c >= 11 && c <= 12) {
    return ['physics', 'chemistry', 'math', 'biology', 'english', 'computer', 'economics'];
  }
  return ['math', 'science', 'english'];
}

